"""Code generation for the flight-controller export: portable C controller, PX4 module
(fw_ss_control, replaces fw_rate_control on fixed-wing), parameter files and a README.

The C step function is the exact counterpart of fcexport.simulate_discrete (same order of
operations), which the tests use as reference."""
import datetime
import os

import numpy as np

from . import fcexport as fx  # noqa: F401  (types used in the docstrings)

PX4_VERSION = "v1.17.0"


def app_version():
    try:
        from version import __version__
        return __version__
    except ImportError:
        return "dev"


def _f(v):
    """C float literal."""
    v = float(v)
    if v == 0.0:
        return "0.0f"
    s = f"{v:.9e}"
    return s + "f"


def _arr(name, M, rows, cols):
    M = np.atleast_2d(np.asarray(M, float)).reshape(rows, cols) if rows and cols else np.zeros((0, 0))
    if rows == 0 or cols == 0:
        return f"/* {name}: empty */\n"
    body = ",\n".join("\t{" + ", ".join(_f(x) for x in row) + "}" for row in M)
    return f"static const float {name}[{rows}][{cols}] = {{\n{body}\n}};\n"


def _vec(name, v):
    v = np.asarray(v, float).ravel()
    if len(v) == 0:
        return f"/* {name}: empty */\n"
    return f"static const float {name}[{len(v)}] = {{" + ", ".join(_f(x) for x in v) + "};\n"


def c_controller(dcs, meta):
    """dcs: list of fcexport.DiscreteController (one per axis). Returns (header, source)."""
    stamp = meta.get("stamp") or datetime.date.today().isoformat()
    head = [f"/* fc_controller.h - generated by SAS & Autopilot Designer {app_version()} on {stamp}",
            f" * Aircraft: {meta.get('name', 'aircraft')}.  Sample time {dcs[0].Ts:g} s.",
            " * Inputs are raw measurements in SI units (rad, rad/s, m/s); trim values are subtracted inside.",
            " * Outputs are normalized torques in [-1, 1] (PX4 vehicle_torque_setpoint convention:",
            " * positive = nose up / right wing down / nose right).",
            " * Call <axis>_reset() when the controller is (re)engaged and <axis>_step() every sample.",
            " */",
            "#ifndef FC_CONTROLLER_H", "#define FC_CONTROLLER_H", "",
            "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
            f"#define FC_TS {_f(dcs[0].Ts)}",
            f"#define FC_TS_US {int(round(dcs[0].Ts * 1e6))}", ""]
    src = [f'/* fc_controller.c - generated by SAS & Autopilot Designer {app_version()} on {stamp}.', " * Do not edit: regenerate from the application. */",
           '#include "fc_controller.h"', "#include <math.h>", ""]
    for dc in dcs:
        P = f"fc_{dc.name}"
        U = P.upper()
        nx, ny, nu = dc.A.shape[0], dc.By.shape[1], dc.C.shape[0]
        nxs = max(nx, 1)
        head += [f"/* {dc.name}: setpoint {dc.r_name} [rad]; measurements "
                 + ", ".join(f"y[{i}] = {nm}" for i, nm in enumerate(dc.y_names))
                 + "; outputs " + ", ".join(f"u[{i}] = {nm}" for i, nm in enumerate(dc.u_names)) + " */",
                 f"#define {U}_NX {nx}", f"#define {U}_NY {ny}", f"#define {U}_NU {nu}",
                 f"typedef struct {{ float x[{nxs}]; float rf; int init; int saturated; }} {P}_t;",
                 f"void {P}_reset({P}_t *s);",
                 f"void {P}_step({P}_t *s, float setpoint, const float y[{U}_NY], float u[{U}_NU]);", ""]
        trim = dc.trim if dc.trim is not None else [0.0] * nu
        src += [f"/* ---- {dc.name} ---- */",
                _arr(f"{P}_A", dc.A, nx, nx), _arr(f"{P}_Br", dc.Br, nx, 1), _arr(f"{P}_By", dc.By, nx, ny),
                _arr(f"{P}_C", dc.C, nu, nx), _arr(f"{P}_Dr", dc.Dr, nu, 1), _arr(f"{P}_Dy", dc.Dy, nu, ny),
                _vec(f"{P}_yoff", dc.y_offsets), _vec(f"{P}_trim", trim),
                f"static const float {P}_roff = {_f(dc.r_offset)};",
                f"static const float {P}_apf = {_f(dc.a_pf)};",
                f"static const int {P}_isint[{nxs}] = {{" + ", ".join("1" if i in dc.int_idx else "0"
                                                                    for i in range(nxs)) + "};", "",
                f"void {P}_reset({P}_t *s)", "{",
                f"\tfor (int i = 0; i < {nxs}; i++) {{ s->x[i] = 0.0f; }}",
                "\ts->rf = 0.0f;", "\ts->init = 0;", "\ts->saturated = 0;", "}", "",
                f"void {P}_step({P}_t *s, float setpoint, const float y[{U}_NY], float u[{U}_NU])", "{",
                f"\tconst float r = setpoint - {P}_roff;",
                "\tif (!s->init) {", f"\t\ts->rf = ({P}_apf > 0.0f) ? r : 0.0f;", "\t\ts->init = 1;", "\t}",
                f"\tconst float rin = ({P}_apf > 0.0f) ? s->rf : r;",
                f"\tfloat yd[{U}_NY];",
                f"\tfor (int j = 0; j < {U}_NY; j++) {{ yd[j] = y[j] - {P}_yoff[j]; }}",
                "\tint sat = 0;",
                f"\tfor (int i = 0; i < {U}_NU; i++) {{",
                f"\t\tfloat v = {P}_trim[i] + {P}_Dr[i][0] * rin;",
                f"\t\tfor (int k = 0; k < {U}_NX; k++) {{ v += {P}_C[i][k] * s->x[k]; }}" if nx else "",
                f"\t\tfor (int j = 0; j < {U}_NY; j++) {{ v += {P}_Dy[i][j] * yd[j]; }}",
                "\t\tif (v > 1.0f) { v = 1.0f; sat = 1; }",
                "\t\telse if (v < -1.0f) { v = -1.0f; sat = 1; }",
                "\t\tu[i] = v;", "\t}"]
        if nx:
            src += [f"\tfloat xn[{U}_NX];",
                    f"\tfor (int i = 0; i < {U}_NX; i++) {{",
                    f"\t\tfloat v = {P}_Br[i][0] * rin;",
                    f"\t\tfor (int k = 0; k < {U}_NX; k++) {{ v += {P}_A[i][k] * s->x[k]; }}",
                    f"\t\tfor (int j = 0; j < {U}_NY; j++) {{ v += {P}_By[i][j] * yd[j]; }}",
                    "\t\txn[i] = v;", "\t}",
                    "\t/* anti-windup: conditional integration (integrators hold while saturated) */",
                    f"\tfor (int i = 0; i < {U}_NX; i++) {{",
                    f"\t\tif (!(sat && {P}_isint[i])) {{ s->x[i] = xn[i]; }}", "\t}"]
        src += [f"\tif ({P}_apf > 0.0f) {{ s->rf = {P}_apf * s->rf + (1.0f - {P}_apf) * r; }}",
                "\ts->saturated = sat;", "}", ""]
    head += ["#ifdef __cplusplus", "}", "#endif", "", "#endif /* FC_CONTROLLER_H */", ""]
    return "\n".join(head), "\n".join(x for x in src if x is not None) + "\n"


