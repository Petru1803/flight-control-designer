_README = """# fw_ss_control - generated flight controller for {name}

Generated by SAS & Autopilot Designer {ver} on {stamp}. Target: PX4 {px4} (fixed-wing).

| Axis | Structure | Sample time |
|---|---|---|
{axes}

The module replaces PX4's attitude + rate loops on a fixed-wing (it publishes
`vehicle_torque_setpoint` and `vehicle_thrust_setpoint`). Attitude setpoints still come from
PX4 (Stabilized mode sticks, TECS / navigation in Altitude, Position, Mission). Manual and Acro
modes pass the sticks straight to the surfaces.

Sensors used: roll/pitch from `vehicle_attitude`, body rates from `vehicle_angular_velocity`,
true airspeed from `airspeed_validated` (design airspeed {V0:.2f} m/s TAS when invalid).

## Build

```bash
./install_into_px4.sh ~/PX4-Autopilot                       # SITL board
./install_into_px4.sh ~/PX4-Autopilot boards/px4/fmu-v6x/default.px4board   # a flight controller
cd ~/PX4-Autopilot && make px4_sitl                          # or make px4_fmu-v6x_default
```

## Run

In the PX4 shell (SITL `pxh>` or MAVLink console):

```
fw_rate_control stop
fw_ss_control start
fw_ss_control status
```

To start it automatically on a flight controller, put the two lines `fw_rate_control stop` and
`fw_ss_control start` in `/fs/microsd/etc/extras.txt`.

## Before flying

1. Fly it in SITL with a model of the same aircraft (see the JSBSim model exported with it).
2. Check the surface directions: a positive pitch torque must raise the nose, a positive roll torque
   must lower the right wing, a positive yaw torque must move the nose right.
3. The maximum deflections used in the design ({dmax}) must match the servo travel set in the
   control-allocation parameters (`CA_SV_CS*`).

This is a design tool. Real flight software needs independent verification, hardware-in-the-loop
tests and flight testing.
"""


def px4_module(dcs, meta):
    """Files of the PX4 module {relative path: text}."""
    ver = app_version()
    stamp = meta.get("stamp") or datetime.date.today().isoformat()
    h, c = c_controller(dcs, {**meta, "stamp": stamp})
    states, resets, steps = [], [], []
    for dc in dcs:
        P = f"fc_{dc.name}"
        states.append(f"\t{P}_t _{dc.name}{{}};")
        resets.append(f"\t{P}_reset(&_{dc.name});")
        ys = ", ".join(_SRC[nm] for nm in dc.y_names)
        sp = "euler_sp.theta()" if dc.name == "pitch" else "euler_sp.phi()"
        if dc.name == "pitch":
            steps += [f"\t\tconst float y_pitch[FC_PITCH_NY] {{{ys}}};",
                      "\t\tfloat u_pitch[FC_PITCH_NU];",
                      f"\t\tfc_pitch_step(&_pitch, {sp}, y_pitch, u_pitch);",
                      "\t\ttorque[1] = u_pitch[0];", ""]
        else:
            steps += [f"\t\tconst float y_roll[FC_ROLL_NY] {{{ys}}};",
                      "\t\tfloat u_roll[FC_ROLL_NU];",
                      f"\t\tfc_roll_step(&_roll, {sp}, y_roll, u_roll);",
                      "\t\ttorque[0] = u_roll[0];", "\t\ttorque[2] = u_roll[1];", ""]
    V0 = meta.get("V0", 20.0)
    files = {
        "CMakeLists.txt": _CMAKE,
        "Kconfig": _KCONFIG,
        "FwSsControl.hpp": _HPP.format(ver=ver, states="\n".join(states)),
        "FwSsControl.cpp": _CPP.format(ver=ver, name=meta.get("name", "aircraft"), V0=_f(V0),
                                       resets="\n".join(resets), steps="\n".join(steps)),
        "fc_controller.h": h,
        "fc_controller.c": c,
        "install_into_px4.sh": _INSTALL.format(px4=PX4_VERSION),
        "README.md": _README.format(
            name=meta.get("name", "aircraft"), ver=ver, stamp=stamp, px4=PX4_VERSION, V0=V0,
            axes="\n".join(f"| {dc.name} | {meta.get('structures', {}).get(dc.name, '')} | {dc.Ts:g} s |"
                           for dc in dcs),
            dmax=", ".join(f"{k} {np.degrees(v):.1f} deg" for k, v in meta.get("dmax", {}).items()
                           if np.isfinite(v))),
    }
    return files


def write_files(folder, files):
    os.makedirs(folder, exist_ok=True)
    out = []
    for rel, text in files.items():
        p = os.path.join(folder, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        out.append(p)
    return out
